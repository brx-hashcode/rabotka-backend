import {
  BadRequestException,
  ConflictException,
  Injectable,
  Logger,
  NotFoundException,
  ServiceUnavailableException,
} from '@nestjs/common';
import {
  PayoutStatus,
  Prisma,
  WalletTransactionType,
  type MobileMoneyPayout,
} from '@prisma/client';
import { PrismaService } from '../../common/services/prisma/prisma.service';
import { PaymentGatewayService } from '../../common/services/payment/payment-gateway.service';
import type { PayoutStatusResult } from '../../common/services/payment/types/payment-gateway.types';
import { LogService } from '../log/log.service';
import { WalletService } from './wallet.service';
import { CFA_CURRENCIES } from '../../common/services/payment/payment-countries';

export type SendPayoutInput = {
  /** Generated by the dialog: a resubmission returns the payout already made. */
  clientRequestId: string;
  amount: number;
  /** The amount typed a second time, as confirmation. */
  confirmAmount: number;
  phone: string;
  operator: string;
  note?: string;
  adminId: string;
};

export type AdminPayoutItem = {
  id: string;
  createdAt: string;
  amount: number;
  currency: string;
  phone: string;
  operator: string;
  country: string;
  note: string | null;
  status: PayoutStatus;
  gateway: string;
  gatewayRef: string | null;
  gatewayTxId: string | null;
  failureReason: string | null;
  completedAt: string | null;
  requestedBy: string | null;
};

/** A pending payout older than this is re-checked when the list is read. */
const RECONCILE_AFTER_MS = 30_000;
/** At most this many pending payouts are re-checked per list read. */
const RECONCILE_BATCH = 5;

type PayoutWithAdmin = MobileMoneyPayout & {
  requested_by: { first_name: string; last_name: string } | null;
};

/**
 * Money sent from the gateway account (pawaPay) to a mobile-money number by
 * an admin.
 *
 * The rules that keep it safe:
 *  - the admin types the amount twice, and it must be covered by both the
 *    Rabotka ledger and the gateway's live balance before anything is sent;
 *  - the dialog's request id is unique, so a double click or a retried request
 *    returns the payout already made instead of sending the money again;
 *  - the ledger is debited once, in the same transaction that claims the
 *    payout PENDING → COMPLETED, so a callback and a manual refresh racing
 *    each other cannot debit twice;
 *  - a status is only ever taken from the gateway's API, never from a
 *    callback body.
 */
@Injectable()
export class MobileMoneyPayoutService {
  private readonly logger = new Logger(MobileMoneyPayoutService.name);

  constructor(
    private readonly prisma: PrismaService,
    private readonly paymentGateway: PaymentGatewayService,
    private readonly walletService: WalletService,
    private readonly logService: LogService,
  ) {}

  async send(input: SendPayoutInput): Promise<AdminPayoutItem> {
    const existing = await this.prisma.mobileMoneyPayout.findUnique({
      where: { client_request_id: input.clientRequestId },
      include: {
        requested_by: { select: { first_name: true, last_name: true } },
      },
    });
    if (existing) return this.toItem(existing);

    const amount = Math.round(input.amount);
    if (!Number.isFinite(amount) || amount <= 0) {
      throw new BadRequestException('Montant invalide.');
    }
    if (Math.round(input.confirmAmount) !== amount) {
      throw new BadRequestException(
        'Le montant de confirmation ne correspond pas.',
      );
    }

    if (!this.paymentGateway.supportsPayouts()) {
      throw new ConflictException(
        "Le moyen de paiement actif ne permet pas d'envoyer de l'argent.",
      );
    }
    const gateway = this.paymentGateway.getActiveMetadata();
    // The live networks, like the checkout — not the gateway's declared list.
    const operators = await this.paymentGateway.activeOperators(CFA_CURRENCIES);
    const operator = operators.find((o) => o.code === input.operator);
    if (!operator) {
      throw new BadRequestException(
        `Opérateur invalide pour ${gateway.label}.`,
      );
    }
    const country =
      operator.country ??
      operator.code.slice(operator.code.lastIndexOf('_') + 1);
    // The network's own franc: XOF in Sénégal, XAF in Congo — same amount.
    const currency = operator.currency ?? 'XAF';

    // Covered by Rabotka's own ledger…
    const ledger = await this.walletService.getMobileMoneyBalance();
    if (ledger.balance < amount) {
      throw new BadRequestException(
        `Solde du registre insuffisant (${ledger.balance.toLocaleString('fr-FR')} FCFA).`,
      );
    }
    // …and by what the gateway actually holds in that country.
    let live: number;
    try {
      const balances = await this.paymentGateway.getBalances(country);
      live = balances
        .filter((b) => b.currency === currency)
        .reduce((sum, b) => sum + Number(b.balance), 0);
    } catch {
      throw new ServiceUnavailableException(
        'Impossible de lire le solde du moyen de paiement. Réessayez.',
      );
    }
    if (live < amount) {
      throw new BadRequestException(
        `Solde ${gateway.label} insuffisant (${live.toLocaleString('fr-FR')} ${currency}).`,
      );
    }

    let payout: MobileMoneyPayout;
    try {
      payout = await this.prisma.mobileMoneyPayout.create({
        data: {
          client_request_id: input.clientRequestId,
          amount,
          currency,
          phone: input.phone.trim(),
          operator: operator.code,
          country,
          note: input.note?.trim() || null,
          gateway: gateway.key,
          requested_by_id: input.adminId,
        },
      });
    } catch (err) {
      // The same request submitted twice at once: return the first one.
      if (
        err instanceof Prisma.PrismaClientKnownRequestError &&
        err.code === 'P2002'
      ) {
        return this.toItem(
          await this.load({ client_request_id: input.clientRequestId }),
        );
      }
      throw err;
    }

    try {
      const result = await this.paymentGateway.initiatePayout({
        amount,
        currency,
        externalId: payout.id,
        phone: payout.phone,
        operator: operator.code,
        description: payout.note ?? undefined,
      });
      payout = await this.prisma.mobileMoneyPayout.update({
        where: { id: payout.id },
        data: { gateway_ref: result.gatewayRef },
      });
    } catch (err) {
      // Refused by the gateway: nothing was sent.
      const reason = err instanceof Error ? err.message : String(err);
      await this.prisma.mobileMoneyPayout.update({
        where: { id: payout.id },
        data: { status: PayoutStatus.FAILED, failure_reason: reason },
      });
      await this.audit('PAYOUT_FAILED', payout.id, input.adminId, { reason });
      throw err instanceof BadRequestException
        ? err
        : new BadRequestException(reason);
    }

    await this.audit('PAYOUT_REQUESTED', payout.id, input.adminId, {
      amount,
      phone: payout.phone,
      operator: operator.code,
      gatewayRef: payout.gateway_ref,
    });
    return this.toItem(await this.load({ id: payout.id }));
  }

  /** Re-reads a pending payout's status from the gateway, and settles it. */
  async refresh(id: string): Promise<AdminPayoutItem> {
    const payout = await this.load({ id });
    if (payout.status === PayoutStatus.PENDING && payout.gateway_ref) {
      const result = await this.paymentGateway.checkPayoutStatus(
        payout.gateway_ref,
      );
      await this.settle(payout, result);
    }
    return this.toItem(await this.load({ id }));
  }

  /**
   * A payout callback, already signature-checked by the controller. Only the
   * id is read from it; the status comes from the gateway's API.
   */
  async handleCallback(payload: Record<string, unknown>): Promise<void> {
    const ref = payload['payoutId'];
    if (typeof ref !== 'string' || !ref) return;
    const payout = await this.prisma.mobileMoneyPayout.findUnique({
      where: { gateway_ref: ref },
      include: {
        requested_by: { select: { first_name: true, last_name: true } },
      },
    });
    if (!payout || payout.status !== PayoutStatus.PENDING) return;
    const result = await this.paymentGateway.checkPayoutStatus(ref);
    await this.settle(payout, result);
  }

  async list(params: {
    page: number;
    limit: number;
    status?: PayoutStatus;
  }): Promise<{
    data: AdminPayoutItem[];
    total: number;
    page: number;
    limit: number;
  }> {
    await this.reconcileStale();

    const where: Prisma.MobileMoneyPayoutWhereInput = params.status
      ? { status: params.status }
      : {};
    const [rows, total] = await Promise.all([
      this.prisma.mobileMoneyPayout.findMany({
        where,
        orderBy: { created_at: 'desc' },
        skip: (params.page - 1) * params.limit,
        take: params.limit,
        include: {
          requested_by: { select: { first_name: true, last_name: true } },
        },
      }),
      this.prisma.mobileMoneyPayout.count({ where }),
    ]);
    return {
      data: rows.map((r) => this.toItem(r)),
      total,
      page: params.page,
      limit: params.limit,
    };
  }

  /**
   * Settles a payout from a status the gateway reported. Idempotent: only a
   * PENDING payout moves, and only once.
   */
  private async settle(
    payout: MobileMoneyPayout,
    result: PayoutStatusResult,
  ): Promise<void> {
    if (result.status === 'COMPLETED') {
      const wallet = await this.walletService.getOrCreateMobileMoneyWallet();
      const settled = await this.prisma.$transaction(async (tx) => {
        const claimed = await tx.mobileMoneyPayout.updateMany({
          where: { id: payout.id, status: PayoutStatus.PENDING },
          data: {
            status: PayoutStatus.COMPLETED,
            gateway_tx_id: result.transactionId ?? null,
            completed_at: new Date(),
          },
        });
        if (claimed.count === 0) return false;
        // The money has left: the ledger records it, whatever its balance.
        await tx.wallet.update({
          where: { id: wallet.id },
          data: { balance: { decrement: Number(payout.amount) } },
        });
        await tx.walletTransaction.create({
          data: {
            wallet_id: wallet.id,
            type: WalletTransactionType.MOBILE_MONEY_WITHDRAWAL,
            amount: payout.amount,
            // Same shape as a manual withdrawal: withdrawal:GATEWAY:NOTE.
            reference_type: [
              'withdrawal',
              payout.gateway,
              payout.note ?? `Payout ${payout.phone}`,
            ].join(':'),
            reference_id: payout.id,
          },
        });
        return true;
      });
      if (settled) {
        await this.audit('PAYOUT_COMPLETED', payout.id, null, {
          amount: Number(payout.amount),
          transactionId: result.transactionId ?? null,
        });
      }
      return;
    }

    if (result.status === 'FAILED') {
      const claimed = await this.prisma.mobileMoneyPayout.updateMany({
        where: { id: payout.id, status: PayoutStatus.PENDING },
        data: {
          status: PayoutStatus.FAILED,
          failure_reason: result.failureReason ?? 'FAILED',
        },
      });
      if (claimed.count > 0) {
        await this.audit('PAYOUT_FAILED', payout.id, null, {
          reason: result.failureReason ?? null,
        });
      }
    }
  }

  /**
   * Pending payouts the callback has not settled (unsigned callbacks, a
   * missed delivery): re-checked a few at a time when the list is read.
   */
  private async reconcileStale(): Promise<void> {
    const stale = await this.prisma.mobileMoneyPayout.findMany({
      where: {
        status: PayoutStatus.PENDING,
        gateway_ref: { not: null },
        created_at: { lt: new Date(Date.now() - RECONCILE_AFTER_MS) },
      },
      orderBy: { created_at: 'asc' },
      take: RECONCILE_BATCH,
    });
    for (const payout of stale) {
      try {
        const result = await this.paymentGateway.checkPayoutStatus(
          payout.gateway_ref!,
        );
        await this.settle(payout, result);
      } catch (err) {
        this.logger.warn(
          `Payout ${payout.id} reconcile failed: ${err instanceof Error ? err.message : String(err)}`,
        );
      }
    }
  }

  private async load(
    where: Prisma.MobileMoneyPayoutWhereUniqueInput,
  ): Promise<PayoutWithAdmin> {
    const payout = await this.prisma.mobileMoneyPayout.findUnique({
      where,
      include: {
        requested_by: { select: { first_name: true, last_name: true } },
      },
    });
    if (!payout) throw new NotFoundException('Paiement sortant introuvable.');
    return payout;
  }

  private toItem(p: PayoutWithAdmin): AdminPayoutItem {
    return {
      id: p.id,
      createdAt: p.created_at.toISOString(),
      amount: Number(p.amount),
      currency: p.currency,
      phone: p.phone,
      operator: p.operator,
      country: p.country,
      note: p.note,
      status: p.status,
      gateway: p.gateway,
      gatewayRef: p.gateway_ref,
      gatewayTxId: p.gateway_tx_id,
      failureReason: p.failure_reason,
      completedAt: p.completed_at?.toISOString() ?? null,
      requestedBy: p.requested_by
        ? `${p.requested_by.first_name} ${p.requested_by.last_name}`.trim()
        : null,
    };
  }

  private async audit(
    action: string,
    payoutId: string,
    adminId: string | null,
    metadata: Record<string, unknown>,
  ): Promise<void> {
    await this.logService
      .create({
        action,
        entityType: 'MobileMoneyPayout',
        entityId: payoutId,
        ...(adminId ? { userId: adminId } : {}),
        metadata,
      })
      .catch(() => undefined);
  }
}
